//! UI language selection for the config GUI.
//!
//! The strings themselves live in `ui/main.slint` as `@tr("...")`
//! literals, with the translations bundled into the binary by
//! `build.rs` from `lang/<tag>/LC_MESSAGES/arcthumb.po`. This module
//! only decides *which* bundled language to show and flips Slint to
//! it:
//!
//! 1. `HKCU\Software\ArcThumb\Language` registry override (a tag from
//!    [`LANGUAGES`], e.g. `"ja"`), set from the language dropdown on
//!    the Display tab.
//! 2. The Windows display languages via `GetUserPreferredUILanguages`,
//!    matched against [`LANGUAGES`] in the user's order of preference.
//! 3. English, the source language of the `.slint` file.
//!
//! Adding a language needs no change here beyond a row in
//! [`NATIVE_NAMES`]; the tag list is generated by `build.rs` from the
//! catalogs it found.

use std::io;

use winreg::RegKey;
use winreg::enums::*;

// `pub const LANGUAGES: &[&str]`: `"en"` followed by every bundled
// catalog's tag in sorted order. Generated by `build.rs`.
include!(concat!(env!("OUT_DIR"), "/bundled_languages.rs"));

const SETTINGS_KEY: &str = "Software\\ArcThumb";
const LANGUAGE_VALUE: &str = "Language";

/// How each language is labelled in the dropdown: in its own
/// language, so a user stuck in a UI they cannot read can still find
/// theirs. Every tag in [`LANGUAGES`] must have a row here; a test
/// checks that, so a new `.po` without a name fails `cargo test`
/// rather than showing up as a blank entry.
const NATIVE_NAMES: &[(&str, &str)] = &[("en", "English"), ("ja", "日本語")];

/// The dropdown label for `tag`. Falls back to the tag itself for a
/// language missing from [`NATIVE_NAMES`] so the entry is at least
/// selectable.
pub fn native_name(tag: &str) -> &str {
    NATIVE_NAMES
        .iter()
        .find(|(t, _)| *t == tag)
        .map_or(tag, |(_, name)| name)
}

/// What the language dropdown is set to.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LanguageChoice {
    /// No override; follow the Windows display language.
    Auto,
    /// A tag from [`LANGUAGES`].
    Fixed(&'static str),
}

impl LanguageChoice {
    /// Position in the language dropdown: 0 is Auto, then the
    /// [`LANGUAGES`] entries in order. Must stay in sync with the
    /// dropdown model built in `ui.rs`.
    pub fn to_index(self) -> i32 {
        match self {
            LanguageChoice::Auto => 0,
            LanguageChoice::Fixed(tag) => LANGUAGES
                .iter()
                .position(|t| *t == tag)
                .map_or(0, |i| i as i32 + 1),
        }
    }

    /// Inverse of [`to_index`](Self::to_index). Any out-of-range index
    /// falls back to [`LanguageChoice::Auto`].
    pub fn from_index(index: i32) -> Self {
        usize::try_from(index)
            .ok()
            .and_then(|i| i.checked_sub(1))
            .and_then(|i| LANGUAGES.get(i))
            .map_or(LanguageChoice::Auto, |tag| LanguageChoice::Fixed(tag))
    }

    /// Parse the registry value. Anything that is not a bundled
    /// language reads as no override. The long forms were what the
    /// first releases documented, so they still parse.
    fn from_registry_value(value: &str) -> Self {
        let value = value.to_ascii_lowercase();
        let tag = match value.as_str() {
            "english" => "en",
            "japanese" | "jp" => "ja",
            other => other,
        };
        bundled_tag(tag).map_or(LanguageChoice::Auto, LanguageChoice::Fixed)
    }

    /// The tag stored in the registry for this choice.
    fn registry_value(self) -> Option<&'static str> {
        match self {
            LanguageChoice::Auto => None,
            LanguageChoice::Fixed(tag) => Some(tag),
        }
    }
}

/// The [`LANGUAGES`] entry equal to `tag`, ignoring case, if any.
fn bundled_tag(tag: &str) -> Option<&'static str> {
    LANGUAGES
        .iter()
        .copied()
        .find(|t| t.eq_ignore_ascii_case(tag))
}

/// The override stored in the registry, [`LanguageChoice::Auto`] when
/// there is none.
pub fn language_override() -> LanguageChoice {
    RegKey::predef(HKEY_CURRENT_USER)
        .open_subkey(SETTINGS_KEY)
        .and_then(|key| key.get_value::<String, _>(LANGUAGE_VALUE))
        .map(|value| LanguageChoice::from_registry_value(&value))
        .unwrap_or(LanguageChoice::Auto)
}

/// Store the override. `Auto` removes the value so the Windows display
/// language decides again.
pub fn set_language_override(choice: LanguageChoice) -> io::Result<()> {
    let (key, _) = RegKey::predef(HKEY_CURRENT_USER).create_subkey(SETTINGS_KEY)?;
    match choice.registry_value() {
        Some(tag) => key.set_value(LANGUAGE_VALUE, &tag),
        None => match key.delete_value(LANGUAGE_VALUE) {
            Err(e) if e.kind() != io::ErrorKind::NotFound => Err(e),
            _ => Ok(()),
        },
    }
}

/// The language tag to show right now.
pub fn resolve() -> &'static str {
    match language_override() {
        LanguageChoice::Fixed(tag) => tag,
        LanguageChoice::Auto => pick_for_os(&os_preferred_ui_languages()),
    }
}

/// Switch the bundled translation to `tag`.
///
/// Slint only knows its bundled languages once the first component
/// exists, so this must run after `MainWindow::new()` and before the
/// window is shown. `tag` comes from [`resolve`], which only returns
/// bundled tags, so the only way this fails is a mismatch between the
/// catalogs `build.rs` saw and the running binary; falling back to
/// English is the right outcome there.
pub fn activate(tag: &str) {
    if let Err(e) = slint::select_bundled_translation(tag) {
        eprintln!("arcthumb-config: could not select language {tag:?}: {e}");
    }
}

/// First entry of [`LANGUAGES`] that matches one of the user's
/// preferred UI languages, most preferred first. A preferred language
/// like `"ja-JP"` matches the bundled `"ja"` by its language part
/// when there is no exact match. English when nothing matches.
fn pick_for_os(preferred: &[String]) -> &'static str {
    fn base(tag: &str) -> &str {
        tag.split(['-', '_']).next().unwrap_or(tag)
    }
    preferred
        .iter()
        .find_map(|pref| {
            bundled_tag(pref).or_else(|| {
                LANGUAGES
                    .iter()
                    .copied()
                    .find(|t| base(t).eq_ignore_ascii_case(base(pref)))
            })
        })
        .unwrap_or("en")
}

/// The user's Windows display languages as BCP-47 tags, most preferred
/// first (e.g. `["ja-JP", "en-US"]`). This is the language Windows
/// itself is shown in, not the regional format: a user can run English
/// Windows with Japanese date formats, and the format locale (which is
/// what Slint's own auto-detection reads) would then pick the wrong UI.
fn os_preferred_ui_languages() -> Vec<String> {
    use windows::Win32::Globalization::{GetUserPreferredUILanguages, MUI_LANGUAGE_NAME};
    use windows_core::PWSTR;

    let mut count = 0u32;
    let mut len = 0u32;
    // First call sizes the buffer, second fills it. The result is a
    // double-NUL-terminated list of NUL-terminated UTF-16 strings.
    if unsafe { GetUserPreferredUILanguages(MUI_LANGUAGE_NAME, &mut count, None, &mut len) }
        .is_err()
    {
        return Vec::new();
    }
    let mut buf = vec![0u16; len as usize];
    if unsafe {
        GetUserPreferredUILanguages(
            MUI_LANGUAGE_NAME,
            &mut count,
            Some(PWSTR(buf.as_mut_ptr())),
            &mut len,
        )
    }
    .is_err()
    {
        return Vec::new();
    }
    buf.split(|&c| c == 0)
        .filter(|s| !s.is_empty())
        .map(String::from_utf16_lossy)
        .collect()
}

/// Title and body for the MessageBox shown when the Slint backend
/// itself fails to start. That is the one message that cannot come
/// from the bundled translations, because there is no Slint to ask,
/// so it is the only user-visible text still hard-coded here.
pub fn gui_init_failure_message() -> (&'static str, &'static str) {
    if resolve() == "ja" {
        (
            "ArcThumb",
            "設定 UI の初期化に失敗しました。グラフィックスバックエンドを開始できませんでした。GPU アクセラレーションが利用できない環境 (Windows Sandbox など) で発生することがあります。",
        )
    } else {
        (
            "ArcThumb",
            "Failed to initialize the configuration UI. The graphics backend could not start. This can happen on systems without GPU acceleration (for example Windows Sandbox).",
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn english_is_first_and_japanese_is_bundled() {
        assert_eq!(LANGUAGES[0], "en");
        assert!(
            LANGUAGES.contains(&"ja"),
            "lang/ja catalog missing: {LANGUAGES:?}"
        );
    }

    #[test]
    fn every_bundled_language_has_a_native_name() {
        for tag in LANGUAGES {
            assert!(
                NATIVE_NAMES.iter().any(|(t, _)| t == tag),
                "add a NATIVE_NAMES row for {tag:?} in locale.rs"
            );
        }
    }

    #[test]
    fn language_choice_index_round_trips() {
        assert_eq!(
            LanguageChoice::from_index(LanguageChoice::Auto.to_index()),
            LanguageChoice::Auto
        );
        for tag in LANGUAGES {
            let choice = LanguageChoice::Fixed(tag);
            assert_eq!(LanguageChoice::from_index(choice.to_index()), choice);
        }
        assert_eq!(LanguageChoice::from_index(-1), LanguageChoice::Auto);
        assert_eq!(LanguageChoice::from_index(99), LanguageChoice::Auto);
    }

    #[test]
    fn language_registry_value_parsing() {
        for v in ["en", "EN", "english"] {
            assert_eq!(
                LanguageChoice::from_registry_value(v),
                LanguageChoice::Fixed("en")
            );
        }
        for v in ["ja", "JA", "japanese", "jp"] {
            assert_eq!(
                LanguageChoice::from_registry_value(v),
                LanguageChoice::Fixed("ja")
            );
        }
        for v in ["", "xx", "auto"] {
            assert_eq!(LanguageChoice::from_registry_value(v), LanguageChoice::Auto);
        }
    }

    #[test]
    fn os_language_matching() {
        let langs = |list: &[&str]| list.iter().map(|s| s.to_string()).collect::<Vec<_>>();
        assert_eq!(pick_for_os(&langs(&["ja-JP", "en-US"])), "ja");
        assert_eq!(pick_for_os(&langs(&["en-US", "ja-JP"])), "en");
        // No bundled match for the first preference: fall through.
        assert_eq!(pick_for_os(&langs(&["xx-XX", "ja-JP"])), "ja");
        assert_eq!(pick_for_os(&langs(&["xx-XX"])), "en");
        assert_eq!(pick_for_os(&langs(&[])), "en");
        assert_eq!(pick_for_os(&langs(&["JA"])), "ja");
    }
}
